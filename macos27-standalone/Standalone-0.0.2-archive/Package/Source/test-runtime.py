"""Build probe, validate core under sanitizers, compare against pinned QEMU TCG.
Generates an EFI embedded probe only after the independent result matches.
"""
from pathlib import Path
import subprocess,struct,json,hashlib
r=Path(__file__).resolve().parent; w=r.parent; t=r/'RuntimeTests'
clang='/Library/Developer/CommandLineTools/usr/bin/clang'
def run(args,**kw):return subprocess.run([str(a) for a in args],check=True,**kw)
run([clang,'-target','aarch64-none-elf','-c',t/'probe.S','-o',t/'probe.o'])
run([w/'deps/bin/ld.lld','-T',t/'probe.ld',t/'probe.o','-o',t/'probe.elf'])
run(['/opt/homebrew/opt/llvm@20/bin/llvm-objcopy','--dump-section','.text='+str(t/'probe.bin'),'--dump-section','.data='+str(t/'data.bin'),t/'probe.elf'])
flags=['-std=c11','-O1','-Wall','-Wextra','-Werror','-fsanitize=address,undefined']
for source,name in [('host-runner.c','host-runner'),('test-core.c','test-core')]:
 run([clang,*flags,r/'a64_core.c',t/source,'-o',t/name])
checks=run([t/'test-core'],capture_output=True,text=True).stdout;print(checks,end='')
run([t/'host-runner',t/'probe.bin',t/'data.bin',t/'interpreter-results.bin'])
original=(t/'probe.bin').read_bytes(); b=bytearray(original)
# Only the comparison wrapper's BRK is changed; QEMU then emits its guest result.
assert struct.unpack_from('<I',b,0xb0)[0]==0xd42004e0
struct.pack_into('<I',b,0xb0,0xd503201f);(t/'reference.bin').write_bytes(b)
p=run([w/'darwin-vm/qemu-sptm/build-dell-host/qemu-system-aarch64','-M','virt','-cpu','cortex-a57','-accel','tcg','-m','64M','-nodefaults','-display','none','-serial','none','-monitor','none','-semihosting-config','enable=on,target=native','-bios',t/'reference.bin','-device','loader,file='+str(t/'data.bin')+',addr=0x41000000,force-raw=on'],capture_output=True,timeout=20)
(t/'qemu-stdout.bin').write_bytes(p.stdout);(t/'qemu-stderr.bin').write_bytes(p.stderr)
expected=(t/'interpreter-results.bin').read_bytes()
assert len(expected)==80 and p.stdout==expected and p.stderr==b'',(p.stdout,p.stderr)
def array(name,data):return 'static const uint8_t '+name+'[] = {\n'+','.join('0x%02x'%v for v in data)+'\n};\n'
(r/'probe_payload.h').write_text('/* Generated by test-runtime.py after QEMU comparison. SPDX-License-Identifier: MIT */\n'+array('probe_code',original)+array('probe_data',(t/'data.bin').read_bytes())+array('probe_expected',expected))
report={'scope':'bounded scalar A64 probe only; no ARM macOS kernel execution','ASanUBSan':'PASS','coreChecks':66,'QEMUDifferential':'PASS: all 80 guest result bytes identical','committedInstructions':69,'probeSHA256':hashlib.sha256(original).hexdigest(),'QEMURevision':subprocess.check_output(['git','rev-parse','HEAD'],cwd=w/'darwin-vm/qemu-sptm',text=True).strip(),'results':list(struct.unpack('<10Q',expected))}
(r/'RUNTIME-VALIDATION.json').write_text(json.dumps(report,indent=2)+'\n');print('PASS independent QEMU TCG comparison')
